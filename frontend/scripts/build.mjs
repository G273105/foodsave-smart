import fs from 'node:fs';
const files=['model.js','api.js','mock.js','app.js'];
const seed=JSON.parse(fs.readFileSync('mocks/products.json','utf8'));
const parts=files.map(file=>fs.readFileSync(''+file,'utf8').replace(/^import .*?;\s*$/gm,'').replace(/\bexport (?=(?:class|function|const)\b)/g,''));
fs.writeFileSync('bundle.js','/* Generated by scripts/build.mjs. Edit source modules, then rebuild. */\n(()=>{\n"use strict";\nwindow.FOODSAVE_SEED='+JSON.stringify(seed)+';\n'+parts.join('\n')+'\nwindow.FOODSAVE_READY=ready;\n})();\n');
console.log('Built browser bundle with embedded review products.');
